#!/usr/bin/env python3
"""Actual disposable OVMF authenticated db update/replay enforcement proof.

First create a base with secure-boot-probe.py. This experiment uses only its
throwaway signing key, enrolled VARS and EFI application. No host efivarfs is
read or written. Trusted and untrusted EFI_AUTH2 envelopes use real detached
PKCS#7 signatures generated by OpenSSL; only the fixed db GUID is exercised.
"""
import argparse
import datetime
import hashlib
import json
from pathlib import Path
import struct
import uuid

SOURCE = r'''
typedef status (*setvar)(u16*,struct guid*,u32,u64,void*);
static struct guid image_security={0xd719b2cb,0x3d3a,0x4596,{0xa3,0xbc,0xda,0xd0,0x0e,0x67,0x65,0x6f}};
static u8 before_db[262144],after_db[262144];
static int equal(u8 *a,u8 *b,u64 size){for(u64 i=0;i<size;i++)if(a[i]!=b[i])return 0;return 1;}
static void update(struct runtime *rt,const char *label,u32 attributes,u8 *auth,u64 auth_size,u8 *expected,u64 expected_size){
 u64 before_size=sizeof(before_db),after_size=sizeof(after_db);u32 before_attr=0,after_attr=0;
 status before=rt->GetVariable((u16*)L"db",&image_security,&before_attr,&before_size,before_db);
 status result=((setvar)rt->SetVariable)((u16*)L"db",&image_security,attributes,auth_size,auth);
 status after=rt->GetVariable((u16*)L"db",&image_security,&after_attr,&after_size,after_db);
 text(label);text(" status=");hex(result);text(" read_before=");hex(before);text(" read_after=");hex(after);
 text(" unchanged=");hex(!before&&!after&&before_size==after_size&&equal(before_db,after_db,before_size));
 text(" expected=");hex(!after&&expected&&after_size==expected_size&&equal(after_db,expected,after_size));text("\n");
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", type=Path, required=True, help="completed secure-boot-probe.py output")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--qemu", default="qemu-system-x86_64")
    parser.add_argument("--code", type=Path, default=Path("/usr/share/edk2/OvmfX64/OVMF_CODE.secboot.fd"))
    parser.add_argument("--timeout", type=float, default=15)
    args = parser.parse_args()
    args.base, args.output = args.base.resolve(), args.output.resolve()
    args.output.mkdir(parents=True, exist_ok=False)
    # Reuse runner/compiler-independent code without importing bytecode beside
    # checked-in sources. Its main() never runs in this namespace.
    module = {"__name__": "secure_boot_probe_helpers"}
    helper_path = Path(__file__).with_name("secure-boot-probe.py")
    exec(compile(helper_path.read_text(), str(helper_path), "exec"), module)
    run, measured = module["run"], module["measured"]
    cert, key = args.base / "cert.pem", args.base / "key.pem"
    run(["openssl", "req", "-new", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "1",
         "-subj", "/CN=qrab untrusted auth update probe/", "-keyout", args.output / "untrusted-key.pem",
         "-out", args.output / "untrusted-cert.pem"])
    (args.output / "untrusted-key.pem").chmod(0o600)
    inventory = json.loads((args.base / "enabled.json").read_text())["variables"]
    original_db = bytes.fromhex(next(v["data"] for v in inventory if v["name"] == "db"))
    image_guid = uuid.UUID("d719b2cb-3d3a-4596-a3bc-dad00e67656f").bytes_le
    pkcs7_guid = uuid.UUID("4aafd29d-68df-49ee-8aa9-347d375665a7").bytes_le
    hash_guid = uuid.UUID("c1c41626-504c-4092-aca9-41f936934328").bytes_le
    owner = uuid.UUID("17b5b3ca-1170-4b35-bf84-91427e1fb028").bytes_le
    def esl(label):
        return hash_guid + struct.pack("<III", 76, 0, 48) + owner + hashlib.sha256(label.encode()).digest()
    append = esl("qrab authenticated append fixture")
    replacement = original_db + append + esl("qrab authenticated replacement fixture")
    now = datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0)
    costs = {}
    def authentication(label, payload, attributes, signing_key, signing_cert, seconds):
        stamp = now + datetime.timedelta(seconds=seconds)
        timestamp = struct.pack("<HBBBBBxIhBB", stamp.year, stamp.month, stamp.day,
                                stamp.hour, stamp.minute, stamp.second, 0, 0, 0, 0)
        signed = "db".encode("utf-16-le") + image_guid + struct.pack("<I", attributes) + timestamp + payload
        (args.output / f"{label}.sign-input").write_bytes(signed)
        _, costs[label] = measured(["openssl", "cms", "-sign", "-binary", "-noattr", "-md", "sha256",
                                    "-signer", signing_cert, "-inkey", signing_key,
                                    "-in", args.output / f"{label}.sign-input", "-outform", "DER",
                                    "-out", args.output / f"{label}.pkcs7"])
        signature = (args.output / f"{label}.pkcs7").read_bytes()
        header = struct.pack("<IHH", 24 + len(signature), 0x0200, 0x0EF1) + pkcs7_guid
        output = timestamp + header + signature + payload
        (args.output / f"{label}.auth").write_bytes(output)
        return output
    bad_before = authentication("bad_before", append, 0x27, args.output / "untrusted-key.pem", args.output / "untrusted-cert.pem", 10)
    good_append = authentication("good_append", append, 0x67, key, cert, 20)
    bad_after = authentication("bad_after", append, 0x67, args.output / "untrusted-key.pem", args.output / "untrusted-cert.pem", 30)
    good_replace = authentication("good_replace", replacement, 0x27, key, cert, 60)
    tampered = bytearray(authentication("tampered", replacement, 0x27, key, cert, 90))
    cert_length = struct.unpack_from("<I", tampered, 16)[0]
    # Flip one signature-value bit while retaining valid DER lengths, the
    # enrolled signer certificate and a fresh timestamp (not a replay).
    tampered[16 + cert_length - 1] ^= 1
    tampered = bytes(tampered)
    (args.output / "tampered.auth").write_bytes(tampered)
    def array(name, data):
        return f"static u8 {name}[]={{" + ",".join(f"0x{b:02x}" for b in data) + "};\n"
    arrays = "".join(array(name, data) for name, data in [
        ("bad_before", bad_before), ("good_append", good_append), ("bad_after", bad_after),
        ("good_replace", good_replace), ("tampered", tampered), ("expected_append", original_db + append), ("expected_replace", replacement)])
    source = module["PROBE"].replace("getvar GetVariable;};", "getvar GetVariable;void *GetNextVariableName,*SetVariable;};")
    source = source.replace("status efi_main(", arrays + SOURCE + "\nstatus efi_main(")
    source = source.replace(" u64 map_size=sizeof(memory_map)", '''
 update(st->runtime,"AuthBadBefore",0x27,bad_before,sizeof(bad_before),0,0);
 update(st->runtime,"AuthGoodAppendBefore",0x67,good_append,sizeof(good_append),expected_append,sizeof(expected_append));
 u64 map_size=sizeof(memory_map)''')
    source = source.replace('  report(st->runtime,(u16*)L"SecureBoot","RuntimeSecureBoot",&global);', '''
  update(st->runtime,"AuthBadAfter",0x67,bad_after,sizeof(bad_after),0,0);
  update(st->runtime,"AuthGoodReplaceAfter",0x27,good_replace,sizeof(good_replace),expected_replace,sizeof(expected_replace));
  update(st->runtime,"AuthTamperedAfter",0x27,tampered,sizeof(tampered),0,0);
  update(st->runtime,"AuthReplayAfter",0x27,good_replace,sizeof(good_replace),0,0);
  report(st->runtime,(u16*)L"SecureBoot","RuntimeSecureBoot",&global);''')
    (args.output / "auth-probe.c").write_text(source)
    run(["clang", "-target", "x86_64-pc-windows-msvc", "-ffreestanding", "-fshort-wchar", "-mno-red-zone",
         "-fno-stack-protector", "-c", args.output / "auth-probe.c", "-o", args.output / "auth-probe.obj"])
    run(["lld-link", "/subsystem:efi_application", "/entry:efi_main", "/nodefaultlib", "/machine:x64",
         f"/out:{args.output / 'auth-probe-unsigned.efi'}", args.output / "auth-probe.obj"])
    run(["sbsign", "--key", key, "--cert", cert, "--output", args.output / "auth-probe-signed.efi",
         args.output / "auth-probe-unsigned.efi"])
    case = module["boot_case"](args, "authenticated-db", args.base / "enabled-signed/vars.fd", args.output / "auth-probe-signed.efi")
    events = {}
    for line in case["debug"].splitlines():
        fields = line.split()
        if fields and fields[0].startswith("Auth"):
            events[fields[0]] = {key: int(value, 16) for key, value in (f.split("=", 1) for f in fields[1:])}
    result = {"qemu_version": run([args.qemu, "--version"]).splitlines()[0],
              "code_sha256": module["sha"](args.code),
              "source_vars_sha256": module["sha"](args.base / "enabled-signed/vars.fd"),
              "public_certificate_sha256": module["sha"](cert), "events": events,
              "signature_helper_cost": costs, "case": case,
              "note": "Replacement replay must be rejected; append timestamps deliberately do not provide replay protection under UEFI."}
    (args.output / "result.json").write_text(json.dumps(result, indent=2))
    print(json.dumps(result, indent=2))
    assert case["probe_executed"], "signed authenticated-update probe did not complete"
    for name in ["AuthBadBefore", "AuthBadAfter", "AuthTamperedAfter", "AuthReplayAfter"]:
        assert events[name]["status"] == 0x800000000000001A, f"{name} did not return EFI_SECURITY_VIOLATION"
        assert events[name]["read_before"] == 0 and events[name]["read_after"] == 0 and events[name]["unchanged"] == 1
    for name in ["AuthGoodAppendBefore", "AuthGoodReplaceAfter"]:
        assert events[name]["status"] == 0 and events[name]["read_after"] == 0 and events[name]["expected"] == 1


if __name__ == "__main__":
    main()
