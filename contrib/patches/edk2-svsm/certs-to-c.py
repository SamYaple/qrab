#!/usr/bin/env python3
"""Render qrab Secure Boot certificates as C source for EnrollDefaultKeys.

OvmfPkg/EnrollDefaultKeys/AuthData.c ships Microsoft KEK + PCA + UefiCA cert
bytes baked in as `CONST UINT8 m*[]` arrays. To make EnrollDefaultKeys.efi
enrol qrab keys instead, we regenerate AuthData.c with our own cert bytes
under the SAME symbol names (so EnrollDefaultKeys.c needs no patching).
mMicrosoftUefiCa is filled with the same qrab db cert (harmless duplicate
enrolment) so the existing enrol-two-db-certs code path stays valid.

Usage:
    certs-to-c.py <keys-dir> <output-auth-data.c>

<keys-dir> must contain PEM certs named KEK.crt and db.crt (the output of
contrib/sb-enroll-keys.sh). Both are converted to DER before embedding.

Exits 0 on success, 1 on missing inputs or openssl failure.
"""
from __future__ import annotations
import argparse
import hashlib
import subprocess
import sys
import textwrap
from datetime import datetime, timezone
from pathlib import Path


def pem_to_der(pem_path: Path) -> bytes:
    """Convert PEM X.509 cert to DER via openssl. No Python ASN.1 dep."""
    result = subprocess.run(
        ["openssl", "x509", "-in", str(pem_path), "-outform", "DER"],
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        raise SystemExit(
            f"openssl failed to convert {pem_path}: {result.stderr.decode()}"
        )
    return result.stdout


def cert_subject(pem_path: Path) -> str:
    """Return the `subject=` line from openssl x509 -noout -subject."""
    result = subprocess.run(
        ["openssl", "x509", "-in", str(pem_path), "-noout", "-subject"],
        capture_output=True,
        check=True,
    )
    return result.stdout.decode().strip().removeprefix("subject=").strip()


def cert_sha1(der_bytes: bytes) -> str:
    return hashlib.sha1(der_bytes).hexdigest()


def format_byte_array(der: bytes, width: int = 13) -> str:
    """Render DER bytes as EDK2-style C array body (13 bytes/line)."""
    lines = []
    for i in range(0, len(der), width):
        chunk = der[i : i + width]
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    # Strip trailing comma on last line for correctness.
    if lines:
        lines[-1] = lines[-1].rstrip(",")
    return "\n".join(lines)


def emit_cert_block(symbol: str, der: bytes, subject: str) -> str:
    sha1 = cert_sha1(der)
    hdr = textwrap.dedent(f"""\
        //
        // {symbol}: qrab-generated certificate
        // SHA1   : {sha1}
        // Subject: {subject}
        //
        CONST UINT8  {symbol}[] = {{
        """)
    body = format_byte_array(der)
    footer = f"\n}};\n\nCONST UINTN  mSizeOf{symbol[1:]} = sizeof {symbol};\n"
    return hdr + body + footer


HEADER = '''\
/** @file
  qrab-generated AuthData for EnrollDefaultKeys.

  This file is GENERATED by contrib/patches/edk2-svsm/certs-to-c.py at build
  time from PEM certs under contrib/sb-keys/. Do NOT edit by hand — your
  changes will be lost on the next build.

  Generated: {generated_at}
  Keys dir : {keys_dir}

  Symbols preserve the upstream AuthData.c names (mMicrosoftKek /
  mMicrosoftPca / mMicrosoftUefiCa) so EnrollDefaultKeys.c needs no
  patching. mMicrosoftUefiCa is set to the same qrab db cert as
  mMicrosoftPca (harmless duplicate enrollment).

  Copyright (C) 2014-2019, Red Hat, Inc. (original MS cert bytes replaced)

  SPDX-License-Identifier: BSD-2-Clause-Patent
**/

#include "EnrollDefaultKeys.h"

'''


DEV_NULL_BLOCK = '''
//
// Dummy dbx entry — SHA256 of /dev/null. Not security-relevant; upstream
// EnrollDefaultKeys requires a non-empty dbx and this is the recommended
// placeholder.
//
CONST UINT8  mSha256OfDevNull[] = {
  0xe3, 0xb0, 0xc4, 0x42, 0x98, 0xfc, 0x1c, 0x14, 0x9a, 0xfb, 0xf4, 0xc8, 0x99,
  0x6f, 0xb9, 0x24, 0x27, 0xae, 0x41, 0xe4, 0x64, 0x9b, 0x93, 0x4c, 0xa4, 0x95,
  0x99, 0x1b, 0x78, 0x52, 0xb8, 0x55
};

CONST UINTN  mSizeOfSha256OfDevNull = sizeof mSha256OfDevNull;
'''


def render(keys_dir: Path) -> str:
    kek_pem = keys_dir / "KEK.crt"
    db_pem = keys_dir / "db.crt"
    for p in (kek_pem, db_pem):
        if not p.is_file():
            raise SystemExit(f"missing cert: {p}")

    kek_der = pem_to_der(kek_pem)
    db_der = pem_to_der(db_pem)
    kek_subject = cert_subject(kek_pem)
    db_subject = cert_subject(db_pem)

    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    header = HEADER.format(generated_at=generated_at, keys_dir=keys_dir)

    return (
        header
        + emit_cert_block("mMicrosoftKek", kek_der, kek_subject)
        + "\n"
        + emit_cert_block("mMicrosoftPca", db_der, db_subject)
        + "\n"
        + emit_cert_block(
            "mMicrosoftUefiCa",
            db_der,
            f"{db_subject}  [duplicate of mMicrosoftPca]",
        )
        + DEV_NULL_BLOCK
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("keys_dir", type=Path, help="directory with PEM certs")
    ap.add_argument("output", type=Path, help="output .c file")
    args = ap.parse_args()

    text = render(args.keys_dir)
    args.output.write_text(text)
    print(f"certs-to-c: wrote {args.output} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
